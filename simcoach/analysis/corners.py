"""Corner detection and track maps.

iRacing does not tell us where the corners are, so we find them on a
reference lap: every significant local minimum of speed is a corner apex.
Each corner owns a *segment* of the lap (from the midpoint with the previous
corner to the midpoint with the next) so that the per-corner time deltas add
up to the whole-lap delta.

Detected maps are saved as YAML so users can rename corners to their real
names ("Turn 1", "La Source", "The Corkscrew") or fix the numbering.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import yaml

from simcoach.analysis.lap import Lap


@dataclass
class Corner:
    number: int
    name: str
    apex_m: float
    start_m: float  # segment start (inclusive)
    end_m: float  # segment end
    aliases: tuple[str, ...] = ()

    def contains(self, d: float) -> bool:
        return self.start_m <= d < self.end_m


@dataclass
class TrackMap:
    track_key: str
    length_m: float
    corners: list[Corner]

    def by_name(self, text: str) -> Corner | None:
        """Find a corner by a spoken reference: 'turn 2', 't2', '2', 'la source'."""
        import re

        t = text.lower().strip()
        m = re.search(r"\b(?:turn|t|corner)\s*(\d+)\b", t) or re.fullmatch(r"(\d+)", t)
        if m:
            n = int(m.group(1))
            for c in self.corners:
                if c.number == n:
                    return c
        for c in self.corners:
            names = [c.name.lower(), *(a.lower() for a in c.aliases)]
            if any(nm and nm in t for nm in names):
                return c
        return None

    def corner_at(self, d: float) -> Corner | None:
        for c in self.corners:
            if c.contains(d):
                return c
        return None

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        data = {
            "track_key": self.track_key,
            "length_m": round(self.length_m, 1),
            "corners": [
                {k: (list(v) if isinstance(v, tuple) else (round(v, 1) if isinstance(v, float) else v))
                 for k, v in asdict(c).items()}
                for c in self.corners
            ],
        }
        header = (
            "# Corner map generated by simcoach. Feel free to edit:\n"
            "#  - rename corners (name) to match the real track, add aliases you might say\n"
            "#  - renumber, merge or delete corners; start_m/end_m are the segment bounds in metres\n"
        )
        path.write_text(header + yaml.safe_dump(data, sort_keys=False), encoding="utf-8")

    @classmethod
    def load(cls, path: Path) -> "TrackMap":
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
        corners = [
            Corner(number=int(c["number"]), name=str(c["name"]), apex_m=float(c["apex_m"]),
                   start_m=float(c["start_m"]), end_m=float(c["end_m"]),
                   aliases=tuple(c.get("aliases") or ()))
            for c in data["corners"]
        ]
        corners.sort(key=lambda c: c.apex_m)
        return cls(track_key=data.get("track_key", ""), length_m=float(data["length_m"]), corners=corners)


def resample(lap: Lap, step_m: float = 1.0) -> tuple[np.ndarray, dict[str, np.ndarray]]:
    grid = np.arange(0.0, lap.length, step_m)
    out = {c: np.interp(grid, lap.dist, getattr(lap, c)) for c in ("speed", "throttle", "brake", "time")}
    return grid, out


def _smooth(x: np.ndarray, n: int) -> np.ndarray:
    if n <= 1 or len(x) < n:
        return x
    kernel = np.ones(n) / n
    pad = n // 2
    xp = np.pad(x, pad, mode="edge")
    return np.convolve(xp, kernel, mode="valid")[: len(x)]


def detect_corners(lap: Lap, track_key: str = "", min_drop_kph: float = 8.0,
                   min_separation_m: float = 120.0, lookback_m: float = 350.0) -> TrackMap:
    """Find corners on a (reference) lap from its speed trace."""
    grid, ch = resample(lap, 1.0)
    if len(grid) < 50:
        return TrackMap(track_key, lap.length, [])
    speed = _smooth(ch["speed"] * 3.6, 25)
    n = len(speed)
    half = 40

    apexes: list[int] = []
    for i in range(1, n - 1):
        lo, hi = max(0, i - half), min(n, i + half + 1)
        if speed[i] > speed[lo:hi].min() + 1e-9:
            continue
        before = speed[max(0, i - int(lookback_m)): i + 1].max()
        after = speed[i: min(n, i + int(lookback_m))].max()
        # Must be a real dip: speed drops into it and recovers after it.
        if before - speed[i] < min_drop_kph or after - speed[i] < min_drop_kph * 0.5:
            continue
        if apexes and i - apexes[-1] < min_separation_m:
            # Keep the slower of two close minima (one corner, e.g. a double apex).
            if speed[i] < speed[apexes[-1]]:
                apexes[-1] = i
            continue
        apexes.append(i)

    apex_m = [float(grid[i]) for i in apexes]
    corners: list[Corner] = []
    for k, a in enumerate(apex_m):
        start = 0.0 if k == 0 else (apex_m[k - 1] + a) / 2
        end = lap.length if k == len(apex_m) - 1 else (a + apex_m[k + 1]) / 2
        corners.append(Corner(number=k + 1, name=f"Turn {k + 1}", apex_m=a, start_m=start, end_m=end))
    return TrackMap(track_key=track_key, length_m=lap.length, corners=corners)
